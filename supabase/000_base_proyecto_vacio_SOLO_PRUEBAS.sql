-- GULA COMANDAS: 000 - TABLAS BASE SOLO PARA PROYECTO DE PRUEBAS VACÍO
-- NO ejecutar en producción. No inserta clientes ni datos reales.
-- Compatible a nivel de columnas con el esquema identificado; falta
-- validar flujos y restricciones antes de instalar las migraciones 001–008.
begin;
create table public.gula_usuarios (
 user_id uuid primary key references auth.users(id) on delete cascade,
 nombre text not null default '',
 rol text not null default 'usuario' check (rol in ('admin','usuario')),
 activo boolean not null default true
);
create table public.gula_productos (
 id uuid primary key default gen_random_uuid(),
 nombre text not null,
 precio integer not null default 0 check(precio>=0),
 activo boolean not null default true,
 creado_en timestamptz not null default now(),
 actualizado_en timestamptz not null default now()
);
create table public.gula_comandas (
 id uuid primary key default gen_random_uuid(),
 numero bigint generated by default as identity unique,
 cliente text not null,
 telefono text not null default '',
 fecha_entrega timestamptz not null,
 tipo_entrega text not null default 'Retiro',
 estado_pago text not null default 'Pendiente',
 notas text not null default '',
 items jsonb not null default '[]'::jsonb,
 total integer not null default 0 check(total>=0),
 creado_por uuid references auth.users(id),
 creado_en timestamptz not null default now(),
 actualizado_en timestamptz not null default now()
);
create table public.gula_configuracion (
 clave text primary key,
 valor jsonb not null default '{}'::jsonb
);
-- Sin políticas y sin grants: acceso desde cliente bloqueado hasta revisión.
alter table public.gula_usuarios enable row level security;
alter table public.gula_productos enable row level security;
alter table public.gula_comandas enable row level security;
alter table public.gula_configuracion enable row level security;
revoke all on public.gula_usuarios,public.gula_productos,
 public.gula_comandas,public.gula_configuracion from anon,authenticated;
-- La secuencia identity tampoco se expone al cliente en esta etapa.
commit;

-- Verificación solo lectura: deben aparecer las cuatro tablas.
select table_name from information_schema.tables
where table_schema='public' and table_name like 'gula_%'
order by table_name;
